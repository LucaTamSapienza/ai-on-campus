export type PlanDocumentData = {
  courseName: string;
  createdLabel: string;
  days: number;
  scopeLabel: string;
  toStudy: number;
  sessionCount: number;
  known: string[];
  knownCount: number;
  sessions: {
    id: string;
    title: string;
    lessons: string;
    concepts: { id: string; name: string; lesson: string | null; noEvidence: boolean }[];
    why: string | null;
    look: { ref: string; source: string; note: string }[];
    withoutEvidence: string[];
  }[];
};

// "2026-11-14 13:43:35" (UTC, da SQLite) diventa "14 November 2026".
export function formatPlanDate(createdAt: string) {
  const d = new Date(`${createdAt.replace(" ", "T")}Z`);
  if (Number.isNaN(d.getTime())) return createdAt;
  return d.toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });
}

// "L01_bandits_regret" diventa "L01 · bandits regret".
function lessonLabel(lesson: StudioOptions["lessons"][number]) {
  const rest = lesson.title.replace(/^L\d+[_\s-]*/i, "").replace(/[_-]+/g, " ").trim();
  return rest ? `${lesson.short} · ${rest}` : lesson.short;
}

export function buildPlanDocument(plan: StudyPlan, courseName: string, options: StudioOptions | null): PlanDocumentData {
  const knownLessons = plan.knownLessons
    .map((id) => options?.lessons.find((l) => l.id === id))
    .filter((l): l is StudioOptions["lessons"][number] => !!l)
    .map((l) => `${lessonLabel(l)} (whole lesson)`);
  const knownConcepts = plan.knownConcepts
    .map((id) => options?.concepts.find((c) => c.id === id)?.name)
    .filter((n): n is string => !!n);
  return {
    courseName,
    createdLabel: formatPlanDate(plan.createdAt),
    days: plan.days,
    scopeLabel: plan.scope === "svolte" ? "Lessons already taught" : "Whole course",
    toStudy: plan.stats.toStudy,
    sessionCount: plan.sessions.length,
    known: [...knownLessons, ...knownConcepts],
    knownCount: plan.stats.known,
    sessions: plan.sessions.map((s) => ({
      id: s.id,
      title: `Day ${s.day} · Session ${s.ordinal}`,
      lessons: [...new Set(s.concepts.map((c) => c.lesson).filter((l): l is string => !!l))].sort().join(", "),
      concepts: s.concepts.map((c) => ({ id: c.id, name: c.name, lesson: c.lesson, noEvidence: c.evidence === 0 })),
      why: s.status === "error" ? null : s.why,
      look: s.look.map((l) => ({ ref: `${shortSource(l.passage.sourceTitle)} · ${l.passage.locator}`, source: l.passage.sourceTitle, note: l.note })),
      withoutEvidence: s.concepts.filter((c) => c.evidence === 0).map((c) => c.name),
    })),
  };
}

export function planFileName(data: PlanDocumentData) {
  const slug = data.courseName.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "course";
  return `prisma-study-plan-${slug}.pdf`;
}
